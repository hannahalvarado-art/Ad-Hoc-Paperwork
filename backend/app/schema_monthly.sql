ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS run_type              TEXT NOT NULL DEFAULT 'manual';
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS actor                 TEXT;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS rows_pulled           INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS rows_excluded         INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS duplicates_removed    INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS final_event_count     INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS customer_count        INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS unresolved_pricing    INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS unresolved_exceptions INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS expected_amount       DOUBLE PRECISION;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS notification_status   TEXT;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS events_added          INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS events_updated        INTEGER;
ALTER TABLE pipeline_runs ADD COLUMN IF NOT EXISTS events_disqualified   INTEGER;

-- ------------------------------------------------------ notification history
-- `kind` distinguishes the once-per-period scheduled review notification from
-- deliberate resends. The partial unique index below is what stops a retrying
-- cron job notifying @csms twice; a resend is a different kind and is free to
-- repeat.
CREATE TABLE IF NOT EXISTS notifications (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_id     INTEGER NOT NULL REFERENCES periods(id) ON DELETE CASCADE,
  kind          TEXT    NOT NULL DEFAULT 'review',   -- 'review' | 'review_resend'
  channel       TEXT,
  mode          TEXT,                                -- dry_run | dev | live
  status        TEXT    NOT NULL,                    -- sent | skipped | failed
  slack_ts      TEXT,
  message       TEXT,
  error         TEXT,
  actor         TEXT,
  run_id        INTEGER REFERENCES pipeline_runs(id),
  created_at    TEXT    NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);

-- One successful scheduled review notification per period. Partial, so failed
-- attempts can be retried and resends are unconstrained.
CREATE UNIQUE INDEX IF NOT EXISTS idx_notify_once
  ON notifications(period_id, kind)
  WHERE kind = 'review' AND status = 'sent';

CREATE INDEX IF NOT EXISTS idx_notify_period ON notifications(period_id, id DESC);
